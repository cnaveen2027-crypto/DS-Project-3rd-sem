export function determineBestAlgorithm(models: ModelEvaluation[]): ModelEvaluation {
  return [...models].sort((a, b) => {
    // Clinical composite weighting: ROC-AUC is prioritized (40%), followed by F1 (30%), Recall (20%), and Accuracy (10%)
    const scoreA = a.rocAuc * 0.4 + a.f1Score * 0.3 + a.recall * 0.2 + a.accuracy * 0.1;
    const scoreB = b.rocAuc * 0.4 + b.f1Score * 0.3 + b.recall * 0.2 + b.accuracy * 0.1;
    return scoreB - scoreA;
  })[0];
}

export function rankAlgorithms(models: ModelEvaluation[]): Array<ModelEvaluation & { compositeScore: number; rank: number }> {
  const ranked = [...models]
    .map((m) => {
      const compositeScore = Number((m.rocAuc * 0.4 + m.f1Score * 0.3 + m.recall * 0.2 + m.accuracy * 0.1).toFixed(2));
      return { ...m, compositeScore, rank: 0 };
    })
    .sort((a, b) => b.compositeScore - a.compositeScore);

  return ranked.map((item, idx) => ({
    ...item,
    rank: idx + 1,
  }));
}
